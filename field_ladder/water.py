"""Section 3.4 water balance and the glide-shortfall example, at R4.

Both were last computed on the former fan geometry. Nothing here is new
physics; it is the same arithmetic on the reference case.
"""
import json, pickle
import numpy as np
import boreas as B
import boreas_ground as G
import packstamp

OUT = 'results_pack_v2'
THUMS = dict(D_in=201.2/25.4, r_casing_o=0.21910/2, r_bore=0.31120/2,
             k_cement=0.7)
CASE = B.Case(n_segments=99, L_ft=1250/0.3048, t_operation_yr=10.0, **THUMS)
rec = pickle.load(open('rec_field.pkl', 'rb'))['rec']
T = rec['T']
M = {}


def add(n, v, fmt='{:.4g}', note=''):
    M[n] = (v if isinstance(v, str) else fmt.format(v), note)


# ---- the water loop, per fin tube -------------------------------------
rho = B.water_rho(CASE, rec['T_2d_realized']) if hasattr(B, 'water_rho') \
    else 1000.0 * 0.95
A_tube = np.pi * CASE.r_i ** 2
for tag, m in (('Ch', rec['m1_ch']), ('Dc', rec['m1_dc'])):
    u = m / (rho * A_tube)
    add(f'Water{tag}Velocity', u, '{:.3f}', 'm/s in one fin tube')
    add(f'Water{tag}Transit', CASE.L_well / u / 60.0, '{:.1f}',
        'one-way transit time, min')
t_half = CASE.t_ch * 3600.0
add('WaterTransitOverHalfCycle',
    (CASE.L_well / (rec['m1_ch'] / (rho * A_tube))) / t_half, '{:.4f}',
    'transit time as a fraction of the half-cycle')

# ---- capacity ratio: water carried against PCM latent inventory -------
m_tot = rec['m1_ch'] * t_half                       # kg through one tube
cp = 4200.0
glide_ch = abs(T['T_3c'] - T['T_2c'])
C_water = m_tot * cp * glide_ch / 1e6               # MJ per tube
V_pcm = CASE.V_well / CASE.n_ft
E_lat = CASE.h_m * 2000.0 * V_pcm / 1e6             # MJ per tube, rho ~ 2000
add('WaterCapacityRatio', C_water / E_lat, '{:.2f}',
    'water enthalpy swept per half-cycle over the latent inventory, '
    'per fin tube')

# ---- the glide shortfall ----------------------------------------------
# What the store actually hands the ORC, against what the glide alone
# would allow if every layer gave up its full span.
dT_avail = abs(rec['T_2d_realized'] - T['T_3d'])
span = CASE.DT_3C_2C * (CASE.N_lay - 1) / CASE.N_lay
ratio_T = dT_avail / span
dE_dc = abs(rec['Q_discharge_kJ'])
dE_in = abs(rec['Q_charge_kJ'])
add('GlideShortfallEnergy', dE_dc / dE_in, '{:.4f}',
    'dE_dc / dE_ch at R4')
add('GlideShortfallTemp', ratio_T, '{:.4f}',
    '(T_2d - T_3d) / span at R4')
add('GlideSpan', span, '{:.2f}', 'cascade span, K')
add('GlideDeltaT', dT_avail, '{:.2f}', 'T_2d - T_3d realised, K')

bad = [n for n, (v, _) in M.items() if str(v).strip().lower()
       in ('nan', 'inf', '-inf', '')]
if bad:
    raise SystemExit('unusable: ' + ', '.join(bad))
with open(f'{OUT}/boreas_water_numbers.tex', 'w') as f:
    f.write(packstamp.stamp())
    f.write('% GENERATED by water.py -- section 3.4, at R4.\n\n')
    for n, (v, note) in sorted(M.items()):
        pad = ' ' * max(1, 30 - len(n))
        f.write(f'\\newcommand{{\\{n}}}{{{v}}}{pad}'
                + (f'% {note}\n' if note else '\n'))
json.dump({n: v for n, (v, _) in M.items()},
          open(f'{OUT}/water_numbers.json', 'w'), indent=1)
print(f'wrote {OUT}/boreas_water_numbers.tex ({len(M)} macros)')
for n, (v, note) in sorted(M.items()):
    print(f'  {n:28s}{v:>10s}  {note}')
