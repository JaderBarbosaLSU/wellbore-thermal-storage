"""Machine-generate the ladder table from ladder_results.csv.

The paper task must \\input this, never transcribe it. Every drift we have
found so far -- 0.17 vs 0.19 %, the disc/rows mix-up, the T-s figure at a
different case from its own table -- came from a number being restated by
hand after being recomputed somewhere else.
"""
import csv

import packstamp

SRC = 'results_pack_v2/ladder_results.csv'
OUT = 'results_pack_v2/tab_ladder.tex'
ORDER = ['R0v', 'R0i', 'R1', 'R2', 'R3', 'R4']
DESC = {
    'R0v': r'isolated, vertical',
    'R0i': r'isolated, S-curve TVD',
    'R1':  r'disc, vertical',
    'R2':  r'double row, vertical',
    'R3':  r'Grissom slots, vertical',
    'R4':  r'Grissom slots, S-curve',
}
L_REF = 1250.0

rows = {r['step']: r for r in csv.DictReader(open(SRC))
        if r['ground'] == 'superposition' and abs(float(r['L_md']) - L_REF) < 1e-6
        and r['casing'] == 'thums'}

t = [packstamp.stamp().rstrip(),
     r'% GENERATED by mktab_ladder.py from ladder_results.csv -- do not edit.',
     r'% Regenerate instead; hand edits will be overwritten and will drift.',
     r'\begin{table}[htbp]', r'\centering',
     r'\caption{The field ladder at $L = \SI{1250}{\meter}$ MD, Grissom '
     r'Island ($N_\mathrm{field} = 363$), equal-temperature superposition, '
     r'THUMS upper-zone casing, $t_\mathrm{op} = \SI{10}{yr}$. Every well '
     r'in the field is a storage well. The idealized rungs are built at the '
     r'\emph{measured} slot spacing, \SI{1.65}{\meter}, so that the step '
     r'from them to the real positions isolates the layout.}',
     r'\label{tab:ladder}', r'\small',
     r'\begin{tabular}{@{}l l r r r r r@{}}', r'\toprule',
     r'step & configuration & loss [\si{\percent}] & $\eta_\mathrm{storage}$ '
     r'& $\eta_\mathrm{RTE}$ & $e^{\prime}$ [\si{\kilo\watt\hour\per\meter}] '
     r'& field [\si{\mega\watt\hour}] \\', r'\midrule']
for s in ORDER:
    if s not in rows:
        continue
    r = rows[s]
    t.append(f"{s} & {DESC[s]} & {100*float(r['loss']):.1f} & "
             f"{float(r['eta_storage']):.3f} & {float(r['RTE']):.3f} & "
             f"{float(r['e_prime']):.3f} & "
             f"{float(r['field_MWh_per_cycle']):.1f} " + r'\\')
t += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
open(OUT, 'w').write('\n'.join(t))
print(f'wrote {OUT} ({len(rows)} rungs)')
