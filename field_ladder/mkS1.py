"""Supplementary material at R4: Table S1 (state points) and Video S1.

Both were last produced on the former reference -- the 1000-well vertical
array in double rows on four islands -- which no longer exists. Table S1
is regenerated from the reference case's REALISED outlet, and the
animation is rendered inside `field_ground` so its depth axis is the true
vertical depth of the S-curve and not measured depth.
"""
import json
import os
import pickle

import numpy as np
import matplotlib
matplotlib.use('Agg')

import boreas as B
import boreas_ground as G
import boreas_plots as BP
import packstamp

OUT = 'results_pack_v2'
CSV = 'THUMS_wells_WellSTAR_clean.csv'
L_MD = 1250.0
THUMS = dict(D_in=201.2 / 25.4, r_casing_o=0.21910 / 2,
             r_bore=0.31120 / 2, k_cement=0.7)
CASE = B.Case(n_segments=99, L_ft=L_MD / 0.3048, t_operation_yr=10.0,
              **THUMS)


def field():
    return G.cached_reference_field(
        B, CASE, CSV, trajectory='s_curve', kop_rule='staggered',
        theta_max=55.0, kop_ft=300.0, L_md=L_MD, ds=G.DS_STATION,
        verbose=False)[:3]


def table_s1(rank, hp, T2d):
    """Table S1: the state points of both cycles, at R4.

    Printed at the REALISED outlet. Drawing the cycles at the provisional
    T_2d while the tables report the realized one is the drift this pack
    exists to prevent, and at R4 the two differ by 30 K.
    """
    L = [packstamp.stamp().rstrip(),
         r'% GENERATED by mkS1.py at the reference case (R4). Do not edit.',
         r'\begin{table}[htbp]', r'\centering', r'\footnotesize',
         r'\setlength{\tabcolsep}{4pt}',
         r'\caption{\emph{Supplementary material.} State points of the two '
         r'cycles at the reference case (R4): 363 Island Grissom slots on '
         r'reconstructed S-curve trajectories, $L = \SI{1250}{\meter}$ MD, '
         r'THUMS upper-zone casing, $t_\mathrm{op} = \SI{10}{yr}$. The '
         r'cycles are evaluated at the \emph{realized} store outlet, '
         r'$\overline{T}_\mathrm{2d} = \SI{' + f'{T2d - 273.15:.2f}' +
         r'}{\celsius}$. The ORC is a double-stage reheat cycle with a '
         r'regenerator (7e--10e); the HTHP is a two-stage flash-economizer '
         r'cycle, in which 7h throttles into a drum at $p_\mathrm{int}$, '
         r'the saturated liquid 9h throttles on to 4h and the flash vapor '
         r'10h rejoins the second stage. States 5h, 6h and 11h coincide.}',
         r'\label{tab:states}',
         r'\begin{tabular}{@{}l r r r r | l r r r r@{}}', r'\toprule',
         r'ORC & $T$ [\si{\celsius}] & $p$ [\si{\bar}] & $h$ '
         r'[\si{\kilo\joule\per\kilogram}] & $s$ '
         r'[\si{\kilo\joule\per\kilogram\per\kelvin}] & HTHP & '
         r'$T$ [\si{\celsius}] & $p$ [\si{\bar}] & $h$ & $s$ \\',
         r'\midrule']
    for i in range(1, 14):
        e, h = f'{i}e', f'{i}h'
        if i <= 10 and f'T_{e}' in rank:
            left = (f'{e} & {rank["T_" + e] - 273.15:.2f} & '
                    f'{rank["p_" + e] / 1e5:.3f} & {rank["h_" + e]:.2f} & '
                    f'{rank["s_" + e] / 1e3:.4f}')
        else:
            left = ' & & & & '
        right = (f'{h} & {hp["T_" + h] - 273.15:.2f} & '
                 f'{hp["p_" + h] / 1e5:.3f} & {hp["h_" + h]:.2f} & '
                 f'{hp["s_" + h] / 1e3:.4f}')
        L.append(left + ' & ' + right + r' \\')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    open(f'{OUT}/tab_states.tex', 'w').write('\n'.join(L))
    print(f'  wrote {OUT}/tab_states.tex (13 state points, both cycles)')


def table_s1_water(T, case):
    """The eight water states, in the Fig. 1 numbering.

    1 is the FIELD OUTLET and 4 the FIELD INLET in both half-cycles. The
    line-loss coils 3c->4c and 1d->2d are placeholders held at zero, so
    T_4c = T_3c and T_2d = T_1d exactly; both pairs are printed anyway,
    because a reader should be able to see the placeholders in the
    bookkeeping rather than take them on trust.
    """
    rows = []
    for tags, lab in ((['1c', '2c', '3c', '4c'], 'charge'),
                      (['1d', '2d', '3d', '4d'], 'discharge')):
        for i, st in enumerate(tags):
            TK = T[f'T_{st}']
            try:
                h = B.water_h(case, TK)      # already kJ/kg
            except Exception:
                h = None
            rows.append((st, lab if i == 0 else '', TK - 273.15,
                         case.P / 1e5, h))
    L = [packstamp.stamp().rstrip(),
         r'% GENERATED by mkS1.py -- the water loop at the reference case.',
         r'\begin{table}[htbp]', r'\centering', r'\footnotesize',
         r'\caption{\emph{Supplementary material.} The water loop at the '
         r'reference case (R4), in the numbering of Fig.~1: \textbf{1 is the '
         r'field outlet and 4 the field inlet} in both half-cycles. The '
         r'line-loss elements $3\mathrm{c}\to4\mathrm{c}$ and '
         r'$1\mathrm{d}\to2\mathrm{d}$ are placeholders held at zero, so '
         r'$T_{4\mathrm{c}}=T_{3\mathrm{c}}$ and '
         r'$T_{2\mathrm{d}}=T_{1\mathrm{d}}$; pump heating is neglected, so '
         r'$T_{1\mathrm{c}}=T_{2\mathrm{c}}$ and '
         r'$T_{4\mathrm{d}}=T_{3\mathrm{d}}$.}',
         r'\label{tab:states-water}',
         r'\begin{tabular}{@{}l l r r r@{}}', r'\toprule',
         r'state & half-cycle & $T$ [\si{\celsius}] & $p$ [\si{\bar}] & '
         r'$h$ [\si{\kilo\joule\per\kilogram}] \\', r'\midrule']
    for st, lab, TC, pbar, h in rows:
        hs = f'{h:.2f}' if h is not None else '--'
        L.append(f'{st} & {lab} & {TC:.2f} & {pbar:.2f} & {hs} ' + r'\\')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    open(f'{OUT}/tab_states_water.tex', 'w').write('\n'.join(L))
    print(f'  wrote {OUT}/tab_states_water.tex (8 water states)')
    return {f'T_{st}': TC for st, _, TC, _, _ in rows}



def main():
    BP.use_paper_style()
    md, Rg, tvd = field()

    # the recorded march, and the cycles at the outlet it realises
    if os.path.exists('rec_field.pkl'):
        rec = pickle.load(open('rec_field.pkl', 'rb'))['rec']
    else:
        with G.field_ground(B, md, Rg, tvd):
            rec = B.simulate_css_corrected(CASE, record=True)
        pickle.dump(dict(rec=rec), open('rec_field.pkl', 'wb'))
    T2d = rec['T_2d_realized']
    rank, hp, _T = B.cycle_state_points(CASE, T_2d=T2d)
    table_s1(rank, hp, T2d)
    water = table_s1_water(_T, CASE)

    # ---- Video S1 --------------------------------------------------
    # Rendered INSIDE field_ground: animate_well takes its depth axis
    # from the model's own formation_profile, which is patched there, so
    # the ordinate is the S-curve's TRUE VERTICAL DEPTH (891 m at 1250 m
    # MD) and not measured depth. Outside the context manager it would
    # silently draw a 1250 m well.
    with G.field_ground(B, md, Rg, tvd):
        zs, _ = BP.depth_axis(B, CASE)
        print(f'  animation depth axis {zs[0]:.0f} -> {zs[-1]:.0f} m TVD')
        for name in ('BOREAS_cycle.mp4', 'BOREAS_cycle.gif'):
            try:
                BP.animate_well(rec, CASE, f'{OUT}/{name}', fps=12,
                                frames_per_half=60)
                print(f'  wrote {OUT}/{name}')
            except Exception as exc:
                print(f'  {name} FAILED: {type(exc).__name__}: {exc}')

    # max(zs) is the DEEPEST SEGMENT CENTRE, which is half a segment
    # above the bottom of the store: 904 m against the 909 m the
    # trajectory reaches at md = L. Both are reported so the 5 m is not
    # mistaken for a disagreement.
    json.dump(water, open(f'{OUT}/water_states.json', 'w'), indent=1)
    # The line-loss placeholders, so the paper can state from the pack that
    # they exist and are zero rather than take it on trust.
    M = {'LineLossCh': 'not computed', 'LineLossDc': 'not computed',
         'LineLossChdT': f'{CASE.line_ch_dT:.1f}',
         'LineLossDcdT': f'{CASE.line_dc_dT:.1f}',
         'LineLossChdp': f'{CASE.line_ch_dp:.0f}',
         'LineLossDcdp': f'{CASE.line_dc_dp:.0f}',
         'VideoFrames': '120', 'VideoFps': '12',
         'VideoDepthBottom': f'{max(zs):.0f}',
         'VideoDepthNote': 'deepest segment centre; the store bottom is '
                           'RefTvdBottom'}
    with open(f'{OUT}/boreas_video_numbers.tex', 'w') as f:
        f.write(packstamp.stamp())
        f.write('% GENERATED by mkS1.py -- Video S1 at R4.\n\n')
        for k, v in sorted(M.items()):
            f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
    json.dump(M, open(f'{OUT}/video_numbers.json', 'w'), indent=1)
    print(f'  wrote {OUT}/boreas_video_numbers.tex')


if __name__ == '__main__':
    main()
