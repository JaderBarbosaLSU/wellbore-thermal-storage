"""orange.json -> boreas_orange_numbers.tex."""
import json
import packstamp
M = json.load(open('orange.json'))
N = json.load(open('orange_notes.json')) if __import__('os').path.exists(
    'orange_notes.json') else {}
import re
bad = [k for k in M if not re.fullmatch(r'[A-Za-z]+', k)]
if bad:
    raise SystemExit('names must be letters only: ' + ', '.join(bad))
bad = [k for k, v in M.items() if not str(v).strip()
       or str(v).strip().lower() in ('nan', 'inf', '-inf')]
if bad:
    raise SystemExit('unusable: ' + ', '.join(bad))
with open('results_pack_v2/boreas_orange_numbers.tex', 'w') as f:
    f.write(packstamp.stamp())
    f.write('% GENERATED by orange.py / mkorange_tex.py -- the section 10\n'
            '% checks. Several are STRINGS, not numbers.\n\n')
    for k, v in sorted(M.items()):
        pad = ' ' * max(1, 30 - len(k))
        note = N.get(k, '')
        f.write(f'\\newcommand{{\\{k}}}{{{v}}}{pad}'
                + (f'% {note}\n' if note else '\n'))
print(f'wrote results_pack_v2/boreas_orange_numbers.tex ({len(M)} macros)')
