"""The T-s figure at R4 (handoff 6). Missing from pack v2.3 entirely.

Drawn at the REALISED outlet of the reference case, not at the
provisional T_2d the exchanger model assumes: at R4 they differ by 30 K,
and a figure drawn at one while the tables report the other is the exact
drift this pack exists to prevent.
"""
import json, os, pickle
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

import boreas as B
import boreas_ground as G
import boreas_plots as BP
import packstamp

OUT = 'results_pack_v2'
CSV = 'THUMS_wells_WellSTAR_clean.csv'
L_MD = 1250.0
THUMS = dict(D_in=201.2/25.4, r_casing_o=0.21910/2, r_bore=0.31120/2,
             k_cement=0.7)
CASE = B.Case(n_segments=99, L_ft=L_MD/0.3048, t_operation_yr=10.0, **THUMS)

BP.use_paper_style()
rec = pickle.load(open('rec_field.pkl', 'rb'))['rec']
T2d = rec['T_2d_realized']
prov = B.cycle_state_points(CASE)[2]['T_2d']
rank, hp, T = B.cycle_state_points(CASE, T_2d=T2d)
print(f'T_2d provisional {prov-273.15:.2f} C, realised at R4 '
      f'{T2d-273.15:.2f} C  ({T2d-prov:+.1f} K)')

fig, ax = plt.subplots(figsize=(7.2, 5.6))
BP.ts_combined(CASE, rank, hp, T, ax=ax, water='glide', model=B)
ax.set_title('')
fig.tight_layout()
fig.savefig(f'{OUT}/BOREAS_Ts_combined_water.pdf')
plt.close(fig)
print(f'  wrote {OUT}/BOREAS_Ts_combined_water.pdf')

fig, _ = BP.ts_both(CASE, rank, hp)
fig.savefig(f'{OUT}/BOREAS_Ts_cycles.pdf')
plt.close(fig)
print(f'  wrote {OUT}/BOREAS_Ts_cycles.pdf')

M = dict(TsTtwod=f'{T2d-273.15:.2f}', TsTtwodProvisional=f'{prov-273.15:.2f}',
         TsTthreee=f"{rank['T_3e']-273.15:.2f}",
         TsEtaORC=f"{rank['rank_eff']:.4f}", TsCOP=f"{hp['hp_cop']:.3f}")
with open(f'{OUT}/boreas_ts_numbers.tex', 'w') as f:
    f.write(packstamp.stamp())
    f.write('% GENERATED by mkts.py -- the T-s figure at R4.\n\n')
    for k, v in sorted(M.items()):
        f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
json.dump(M, open(f'{OUT}/ts_numbers.json', 'w'), indent=1)
print(f'  wrote {OUT}/boreas_ts_numbers.tex ({len(M)} macros)')
