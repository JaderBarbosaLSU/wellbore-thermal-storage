# ----------------------------------------------------- tab_ref_results --
def tab_ref_results(res):
    def col(key):
        c, r, k = res[key]
        N = r['N_wells']
        MWh = lambda J: J / 3.6e6 / N          # kJ -> MWh per well
        return {
            r'charge flow per fin tube [\si{kg/s}]': (r['m1_ch'], 4),
            r'discharge flow per fin tube [\si{kg/s}]': (r['m1_dc'], 4),
            r'$\Delta E_\mathrm{ch}$ [\si{MWh/well}]': (MWh(r['Q_charge_kJ']), 3),
            r'$\Delta E_\mathrm{dc}$ [\si{MWh/well}]': (MWh(r['Q_discharge_kJ']), 3),
            r'$Q_\mathrm{loss,ch}$ [\si{MWh/well}]': (MWh(r['Q_loss_ch_kJ']), 3),
            r'$Q_\mathrm{loss,dc}$ [\si{MWh/well}]': (MWh(r['Q_loss_dc_kJ']), 3),
            r'$\overline{T}_\mathrm{2c}$ [\si{\degreeCelsius}]':
                (r['T_2c_realized'] - 273.15, 1),
            r'$\overline{T}_\mathrm{2d}$ [\si{\degreeCelsius}]':
                (r['T_2d_realized'] - 273.15, 1),
            '$\\varepsilon_\\mathrm{ch}$':
                (float(r['charge']['eps_local'].mean()), 4),
            '$\\varepsilon_\\mathrm{dc}$':
                (float(r['discharge']['eps_local'].mean()), 4),
            '$\\eta_\\mathrm{T}$': (k['eta_T'], 4),
            '$\\eta_\\mathrm{T,eff}$': (k['eta_T_eff'], 4),
            '$\\eta_\\mathrm{storage}$': (r['eta_storage'], 4),
            '$\\eta_\\mathrm{RTE}$': (k['eta_RTE'], 4),
            '$\\varepsilon_\\mathrm{RTE}$': (k['eps_RTE'], 4),
            r"$e'$ [\si{kWh/m}]": (k['kWh_per_m_well'], 4),
            r'$\rho_E$ [\si{kWh/m^3}]': (k['rho_E_kWh_m3'], 2),
            r'storage wells [\si{1/MW}]': (k['wells_per_MWe'], 1),
            r'geothermal wells [\si{1/MW}]': (k['N_geo_per_MWe'], 1),
            r'all wells [\si{1/MW}]': (k['wells_total_per_MWe'], 1),
            r'pumping [\si{\percent} of gross]': (100 * k['f_pump'], 2),
            r'downcomer leakage [\si{\percent} of $\Delta E_\mathrm{ch}$]':
                (100 * k['f_bypass'], 2),
            r'deviation $\mathcal{D}$ [\si{\percent}]':
                (100 * r['deviation'], 2),
            r'cycles to CSS': (float(r['cycles']), 0),
            r'energy convergence, last 5 cycles [-]': (energy_conv(r), 1),
            r'charge closure [-]': (abs(r['charge']['closure']), 1),
        }
    cols = {k_: col(k_) for k_, _ in ORDER}
    names = list(cols['R4'].keys())
    rows = []
    for n in names:
        cells = []
        for k_, _ in ORDER:
            v, d = cols[k_][n]
            cells.append(f'{v:.{d}e}' if n.endswith('[-]') else f(v, d))
        rows.append([n] + cells)
    tex_table(f'{OUT}/tab_ref_results.tex',
              'The reference case per storage well. Columns: the adiabatic '
              'limit ($k_r \\to 0$); \\textbf{R4}, the reference case, '
              '363 Grissom slots on reconstructed S-curve trajectories; '
              '\\textbf{R3}, vertical wells on the same slots; '
              '\\textbf{R0v}, one isolated vertical well. $L = 1250$ m MD, '
              '$t_\\mathrm{op} = 10$ yr, THUMS casing. No well counts and no '
              'field totals: every row is intensive.',
              'tab:ref-results',
              ['quantity', '{adiabatic}', '{R4}', '{R3}', '{R0v}'], rows,
              align='l' + 'r' * len(ORDER), small=True,
              note='Per-MWe rows are on the realized net output '
                   '$W_\\mathrm{net} = W^{*}_\\mathrm{el,out} - '
                   'W_\\mathrm{f,dc}$.')
    return cols


# ------------------------------------------------- composite curves ----
def composites(res):
    """comp_{a,b,c}{1,2}.pdf -- ONE FILE PER PANEL (handoff 6.7).

    Two panels per case: 1 is the exchanger, 2 is the local approach
    along it. The pair is the point -- the composite alone does not show
    that the minimum is INTERIOR, at the onset of boiling. No panel
    letters and no suptitles in the images; the paper supplies those.

    The two axes handed to `orc_composite` live on DIFFERENT figures, so
    each panel is drawn natively into its own file. Copying artists out
    of a two-panel figure afterwards loses the pinch annotation and the
    guide lines, which are most of what panel 2 is for.
    """
    import boreas_plots as BP
    BP.use_paper_style()
    panels = [('a', 'adiabatic'), ('b', 'R4'), ('c', 'R3')]
    lo, hi = np.inf, -np.inf
    for _, key in panels:
        c, r, k = res[key]
        lo = min(lo, c.T_sink_C, r['rank']['T_1e'] - 273.15)
        hi = max(hi, r['T_2d_realized'] - 273.15)
    lo, hi = lo - 5.0, hi + 8.0
    info = {}
    for tag, key in panels:
        c, r, k = res[key]
        f1, ax1 = plt.subplots(figsize=(4.9, 3.9))
        f2, ax2 = plt.subplots(figsize=(4.9, 3.9))
        _, nfo = BP.orc_composite(B, c, r['rank'], r['T'], axes=[ax1, ax2])
        ax1.set_ylim(lo, hi)              # shared temperature range
        for ax in (ax1, ax2):
            ax.set_title('')
        # legend in the first panel of the row only
        if tag != 'a' and ax1.get_legend() is not None:
            ax1.get_legend().remove()
        for f, sub in ((f1, 1), (f2, 2)):
            f.tight_layout()
            f.savefig(f'{OUT}/comp_{tag}{sub}.pdf')
            plt.close(f)
        info[key] = nfo
        print(f'  wrote {OUT}/comp_{tag}1.pdf and comp_{tag}2.pdf  '
              f'pinch {nfo["pinch_K"]:.2f} K at {nfo["pinch_at_pct"]:.1f} % '
              f'duty', flush=True)
    json.dump({k: {kk: float(vv) for kk, vv in v.items()}
               for k, v in info.items()},
              open(f'{OUT}/composites.json', 'w'), indent=1)
    return info


def main():
    os.makedirs(OUT, exist_ok=True)
    print('running the four cases...', flush=True)
    res = run_all()
    for key, lab in ORDER:
        c, r, k = res[key]
        print(f"  {lab:34s} loss {100*k['f_formation_loss']:6.2f} %  "
              f"T_2d {r['T_2d_realized']-273.15:6.2f} C  "
              f"eta_ORC {r['rank']['rank_eff']:.4f}  "
              f"wells/MWe {k['wells_per_MWe']:6.2f}", flush=True)
    tab_cycles(res); tab_UA(res); tab_T3e(res)
    tab_cycle_states(res)
    cols = tab_ref_results(res)
    try:
        composites(res)
    except Exception as e:
        print('  composites FAILED:', type(e).__name__, e)
    # dump the raw numbers so the macros and the paper can read them
    # Plain keys, not the LaTeX row labels. mknumbers.py read the labels
    # in v2.1 and broke the moment the table gained siunitx units -- and
    # the failure was a macro silently set to nan, not an error.
    PLAIN = [
        ('m1_ch', 'charge flow per fin tube'),
        ('m1_dc', 'discharge flow per fin tube'),
        ('dE_ch_MWh', '$\\Delta E_\\mathrm{ch}$'),
        ('dE_dc_MWh', '$\\Delta E_\\mathrm{dc}$'),
        ('Qloss_ch_MWh', '$Q_\\mathrm{loss,ch}$'),
        ('Qloss_dc_MWh', '$Q_\\mathrm{loss,dc}$'),
        ('T2c_C', '$\\overline{T}_\\mathrm{2c}$'),
        ('T2d_C', '$\\overline{T}_\\mathrm{2d}$'),
        ('eps_ch', '$\\varepsilon_\\mathrm{ch}$'),
        ('eps_dc', '$\\varepsilon_\\mathrm{dc}$'),
        ('eta_T', '$\\eta_\\mathrm{T}$'),
        ('eta_T_eff', '$\\eta_\\mathrm{T,eff}$'),
        ('eta_storage', '$\\eta_\\mathrm{storage}$'),
        ('eta_RTE', '$\\eta_\\mathrm{RTE}$'),
        ('eps_RTE', '$\\varepsilon_\\mathrm{RTE}$'),
        ('e_prime', "$e'$"),
        ('rho_E', '$\\rho_E$'),
        ('wells_per_MWe', 'storage wells'),
        ('N_geo_per_MWe', 'geothermal wells'),
        ('wells_total_per_MWe', 'all wells'),
        ('pumping_pct', 'pumping'),
        ('leakage_pct', 'downcomer leakage'),
        ('deviation', r'deviation $\\mathcal{D}$'),
        ('cycles', 'cycles to CSS'),
        ('energy_conv_last5', 'energy convergence'),
        ('closure', 'charge closure'),
    ]
    dump = {}
    for key, _ in ORDER:
        d, src = {}, cols[key]
        for plain, stem in PLAIN:
            hit = [v for kk, v in src.items() if kk.startswith(stem)]
            if hit:
                v = hit[0][0]
                d[plain] = float(v) if np.isfinite(v) else None
        dump[key] = d
    for key, _ in ORDER:
        c, r, k = res[key]
        dump[key]['UA_per_MWe'] = k['UA_per_MWe']
        dump[key]['eta_ORC'] = r['rank']['rank_eff']
        dump[key]['T_3e_C'] = r['rank']['T_3e'] - 273.15
        dump[key]['W_net_kW'] = k['W_net_kW']
        # MW per MWe. This was missing, which is why \RefHTHPInputPerMWe
        # came out as nan while tab_cycles printed 6.885 from the same run.
        dump[key]['HTHP_in_MW_per_MWe'] = k['W_el_in_per_MWe'] / 1000.0
        dump[key]['m_w_ch_per_MWe'] = k['m_w_ch_per_MWe']
        dump[key]['m_w_dc_per_MWe'] = k['m_w_dc_per_MWe']
        dump[key]['cycles'] = float(r['cycles'])
        dump[key]['energy_conv_last5'] = energy_conv(r)
        dump[key]['deviation'] = 100.0 * r['deviation']
        for _, tag in EXCH:
            dump[key][f'Q_{tag}_over_Wnet'] = k[f'Q_{tag}_over_Wnet']
            dump[key][f'UA_{tag}_per_MWe'] = k[f'UA_{tag}_per_MWe']
    json.dump(dump, open(f'{OUT}/intensive.json', 'w'), indent=1)
    # the cycle indicators as data, for the macros
    _c, _r, _k = res['R4']
    json.dump({k: float(v) for k, v in (
        ('hp_cop', _r['hp']['hp_cop']), ('y_frac', _r['rank']['y_frac']),
        ('x_8h', _r['hp']['x_8h']),
        ('epsilon_IHX_1', _r['hp']['epsilon_IHX_1']),
        ('epsilon_IHX_2', _r['hp']['epsilon_IHX_2']),
        ('p_evape', _r['rank']['p_evape']), ('p_inte', _r['rank']['p_inte']),
        ('p_conde', _r['rank']['p_conde']),
        ('p_evaph', _r['hp']['p_evaph']), ('p_inth', _r['hp']['p_inth']),
        ('p_condh', _r['hp']['p_condh']))},
        open(f'{OUT}/cycle_states.json', 'w'), indent=1)
    print(f'  wrote {OUT}/intensive.json')
    # The headline, printed so it cannot drift from the numbers above.
    a, r4 = res['adiabatic'][2], res['R4'][2]
    print('\n  only the ORC conversion is insensitive to the loss:')
    print(f"    eta_ORC      {res['adiabatic'][1]['rank']['rank_eff']:.4f} "
          f"-> {res['R4'][1]['rank']['rank_eff']:.4f}  "
          f"({100*(res['R4'][1]['rank']['rank_eff']/res['adiabatic'][1]['rank']['rank_eff']-1):+.0f} %)")
    print(f"    eta_RTE      {a['eta_RTE']:.4f} -> {r4['eta_RTE']:.4f}  "
          f"({100*(r4['eta_RTE']/a['eta_RTE']-1):+.0f} %)")
    print(f"    HTHP in      {a['W_el_in_per_MWe']/1000:.2f} -> "
          f"{r4['W_el_in_per_MWe']/1000:.2f} MW per MWe  "
          f"({r4['W_el_in_per_MWe']/a['W_el_in_per_MWe']:.1f}x)")
    print(f"    wells/MWe    {a['wells_per_MWe']:.1f} -> "
          f"{r4['wells_per_MWe']:.1f}  "
          f"({r4['wells_per_MWe']/a['wells_per_MWe']:.1f}x)")
    print('  the loss is paid twice: in wells AND in charged electricity.')


if __name__ == '__main__':
    main()
