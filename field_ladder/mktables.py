"""The intensive tables of handoff section 2b.

Four cases, all at L = 1250 m MD, t_op = 10 yr, THUMS casing:

    adiabatic   k_rock -> 0, the upper bound with no formation at all
    R4          the REFERENCE CASE: Grissom slots, S-curve trajectories
    R3          vertical wells on the same slots, the comparison case
    R0v         one isolated vertical well, the lower bound

Everything per MWe is on the realized-net basis W_net = W*_el,out - W_f,dc
(performance_indices.per_MWe). Everything per well is per STORAGE well.
Nothing here is extensive: no N_w, no field totals.
"""
import json, os
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import rcParams

import boreas as B
import boreas_ground as G

OUT = 'results_pack_v2'
CSV = 'THUMS_wells_WellSTAR_clean.csv'
L_MD = 1250.0
THUMS = dict(D_in=201.2 / 25.4, r_casing_o=0.21910 / 2,
             r_bore=0.31120 / 2, k_cement=0.7)

rcParams.update({'pdf.fonttype': 42, 'ps.fonttype': 42, 'font.family': 'serif',
                 'font.serif': ['Times New Roman', 'Nimbus Roman',
                                'Liberation Serif', 'DejaVu Serif'],
                 'mathtext.fontset': 'stix', 'axes.spines.top': False,
                 'axes.spines.right': False, 'savefig.bbox': 'tight',
                 'savefig.dpi': 300, 'font.size': 9})
RED, NAVY, GREEN, GREY = '#b03028', '#23356b', '#2f6f4f', '#6a6a6a'

CASE = B.Case(n_segments=99, L_ft=L_MD / 0.3048, t_operation_yr=10.0, **THUMS)


def field(trajectory):
    return G.cached_reference_field(B, CASE, CSV, trajectory=trajectory,
                                    kop_rule='staggered', theta_max=55.0,
                                    kop_ft=300.0, L_md=L_MD, ds=50.0,
                                    verbose=False)


def run_all():
    """The four cases, each a full CSS march with its own indices."""
    out = {}
    # --- adiabatic: no formation at all
    c = CASE.with_(k_rock=1e-9)
    r = B.simulate_css_corrected(c)
    out['adiabatic'] = (c, r, B.performance_indices(c, r))
    # --- R0v: isolated vertical well, no field
    r = B.simulate_css_corrected(CASE)
    out['R0v'] = (CASE, r, B.performance_indices(CASE, r))
    # --- R3 and R4: inside the measured field
    for step, traj in (('R3', 'vertical'), ('R4', 's_curve')):
        md, Rg, tvd, _ = field(traj)
        with G.field_ground(B, md, Rg, tvd):
            r = B.simulate_css_corrected(CASE)
            k = B.performance_indices(CASE, r)
        out[step] = (CASE, r, k)
    return out


# ------------------------------------------------------------- latex ----
def tex_table(path, caption, label, header, rows, align=None, note=None):
    n = len(header)
    align = align or ('l' + 'r' * (n - 1))
    with open(path, 'w') as f:
        f.write(f'% GENERATED by mktables.py -- do not edit, do not retype.\n')
        f.write('\\begin{table}[htbp]\n\\centering\n')
        f.write(f'\\caption{{{caption}}}\n\\label{{{label}}}\n')
        f.write(f'\\begin{{tabular}}{{{align}}}\n\\hline\n')
        f.write(' & '.join(header) + ' \\\\\n\\hline\n')
        for row in rows:
            f.write(' & '.join(row) + ' \\\\\n')
        f.write('\\hline\n\\end{tabular}\n')
        if note:
            f.write(f'\\\\[2pt]\\footnotesize {note}\n')
        f.write('\\end{table}\n')
    print(f'  wrote {path}')


def f(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return '--'
    return f'{x:.{d}f}'


# ---------------------------------------------------------- tab_cycles --
EXCH = [('HTHP evaporator', 'hpe'), ('HTHP condenser', 'hpc'),
        ('ORC evaporator', 'orce'), ('ORC condenser', 'orcc')]


def tab_cycles(res):
    """Duties and flows, all intensive.

    There is no separate "per MWe" column for the duties, because
    $Q/W_\\mathrm{net}$ IS the duty in MW per MWe -- the ratio is already
    dimensionless and a second column would print the same number twice.
    """
    c, r, k = res['R4']
    rows = []
    for name, tag in EXCH:
        rows.append([f'{name} duty, $Q/W_\\mathrm{{net}}$',
                     f(k[f'Q_{tag}_over_Wnet'], 2)])
    rows.append(['HTHP electrical input, MW per MWe',
                 f(k['W_el_in_per_MWe'] / 1000.0, 3)])
    rows.append(['charging water flow, kg\\,s$^{-1}$ per MWe',
                 f(k['m_w_ch_per_MWe'], 2)])
    rows.append(['discharging water flow, kg\\,s$^{-1}$ per MWe',
                 f(k['m_w_dc_per_MWe'], 2)])
    rows.append(['\\hline charge flow per fin tube, kg\\,s$^{-1}$',
                 f(r['m1_ch'], 4)])
    rows.append(['discharge flow per fin tube, kg\\,s$^{-1}$',
                 f(r['m1_dc'], 4)])
    tex_table(f'{OUT}/tab_cycles.tex',
              'Plant duties and flows at the reference case (R4), on an '
              'intensive basis. $W_\\mathrm{net}$ is the realized net output, '
              '$W^{*}_\\mathrm{el,out} - W_\\mathrm{f,dc}$. The HTHP input of '
              f"{k['W_el_in_per_MWe']/1000.0:.2f} MW per MWe is the "
              'reciprocal of $\\eta_\\mathrm{RTE}$ to within the pumping term.',
              'tab:cycles', ['quantity', 'value'], rows, align='lr',
              note='The per-tube flows are the two rows that are NOT per '
                   'MWe, and they do not scale with plant size at all: they '
                   'are pinned by the water glide (Eq.~\\ref{eq:mdot-int}).')


# -------------------------------------------------------------- tab_UA --
def tab_UA(res):
    c, r, k = res['R4']
    rows = []
    for name, tag in EXCH:
        rows.append([name, f(k[f'Q_{tag}_over_Wnet'], 2),
                     f(k[f'UA_{tag}_per_MWe'], 1),
                     f(k[f'dTeff_{tag}_K'], 2), f(k[f'pinch_{tag}_K'], 2)])
    rows.append(['\\hline total', '--', f(k['UA_per_MWe'], 1), '--',
                 f(k['pinch_min_K'], 2)])
    tex_table(f'{OUT}/tab_UA.tex',
              'Exchanger conductance at the reference case (R4), per MWe of '
              'realized net output. $\\Delta T_\\mathrm{eff}$ and the pinch '
              'are intensive already and are unchanged.',
              'tab:UA',
              ['exchanger', '$Q/W_\\mathrm{net}$',
               'UA, kW\\,K$^{-1}$ per MWe',
               '$\\Delta T_\\mathrm{eff}$, K', 'pinch, K'], rows)


# ------------------------------------------------------------ tab_T3e --
ORDER = [('adiabatic', 'adiabatic ($k_r \\to 0$)'),
         ('R4', 'reference case (R4)'),
         ('R3', 'vertical wells, same slots (R3)'),
         ('R0v', 'isolated vertical well (R0v)')]


def tab_T3e(res):
    rows = []
    for key, label in ORDER:
        c, r, k = res[key]
        rows.append([label, f(r['T_2d_realized'] - 273.15, 1),
                     f(r['rank']['T_3e'] - 273.15, 1),
                     f(r['rank']['rank_eff'], 4)])
    tex_table(f'{OUT}/tab_T3e.tex',
              'What the store delivers and what the ORC can do with it. '
              '$L = 1250$ m MD, $t_\\mathrm{op} = 10$ yr, THUMS casing. '
              '$T_\\mathrm{3e}$ is set by the evaporator pinch, not by the '
              'hot-end rule.',
              'tab:T3e',
              ['case', '$\\overline{T}_\\mathrm{2d}$, $^\\circ$C',
               '$T_\\mathrm{3e}$, $^\\circ$C', '$\\eta_\\mathrm{ORC}$'], rows)


# ----------------------------------------------------- tab_ref_results --
def tab_ref_results(res):
    def col(key):
        c, r, k = res[key]
        N = r['N_wells']
        MWh = lambda J: J / 3.6e6 / N          # kJ -> MWh per well
        return {
            'charge flow per fin tube, kg/s': (r['m1_ch'], 4),
            'discharge flow per fin tube, kg/s': (r['m1_dc'], 4),
            '$\\Delta E_\\mathrm{ch}$, MWh per well': (MWh(r['Q_charge_kJ']), 3),
            '$\\Delta E_\\mathrm{dc}$, MWh per well': (MWh(r['Q_discharge_kJ']), 3),
            '$Q_\\mathrm{loss,ch}$, MWh per well': (MWh(r['Q_loss_ch_kJ']), 3),
            '$Q_\\mathrm{loss,dc}$, MWh per well': (MWh(r['Q_loss_dc_kJ']), 3),
            '$\\overline{T}_\\mathrm{2c}$, $^\\circ$C':
                (r['T_2c_realized'] - 273.15, 1),
            '$\\overline{T}_\\mathrm{2d}$, $^\\circ$C':
                (r['T_2d_realized'] - 273.15, 1),
            '$\\varepsilon_\\mathrm{ch}$':
                (float(r['charge']['eps_local'].mean()), 4),
            '$\\varepsilon_\\mathrm{dc}$':
                (float(r['discharge']['eps_local'].mean()), 4),
            '$\\eta_\\mathrm{T}$': (k['eta_T'], 4),
            '$\\eta_\\mathrm{T,eff}$': (k['eta_T_eff'], 4),
            '$\\eta_\\mathrm{storage}$': (r['eta_storage'], 4),
            '$\\eta_\\mathrm{RTE}$': (k['eta_RTE'], 4),
            '$\\varepsilon_\\mathrm{RTE}$': (k['eps_RTE'], 4),
            "$e'$, kWh per m of well": (k['kWh_per_m_well'], 4),
            '$\\rho_E$, kWh\\,m$^{-3}$': (k['rho_E_kWh_m3'], 2),
            'storage wells per MWe': (k['wells_per_MWe'], 1),
            'geothermal wells per MWe': (k['N_geo_per_MWe'], 1),
            'all wells per MWe': (k['wells_total_per_MWe'], 1),
            'pumping, \\% of gross output': (100 * k['f_pump'], 2),
            'downcomer leakage, \\% of $\\Delta E_\\mathrm{ch}$':
                (100 * k['f_bypass'], 2),
            'cycles to CSS': (float(r['cycles']), 0),
            'charge closure': (abs(r['charge']['closure']), 1),
        }
    cols = {k_: col(k_) for k_, _ in ORDER}
    names = list(cols['R4'].keys())
    rows = []
    for n in names:
        cells = []
        for k_, _ in ORDER:
            v, d = cols[k_][n]
            cells.append(f'{v:.{d}e}' if n == 'charge closure' else f(v, d))
        rows.append([n] + cells)
    tex_table(f'{OUT}/tab_ref_results.tex',
              'The reference case (R4) per storage well, with vertical wells '
              'on the same slots (R3) and the adiabatic limit as comparison '
              'columns. $L = 1250$ m MD. No well counts and no field totals: '
              'every row is intensive.',
              'tab:ref_results',
              ['quantity'] + [lab for _, lab in ORDER], rows,
              align='l' + 'r' * len(ORDER),
              note='Per-MWe rows are on the realized net output '
                   '$W_\\mathrm{net} = W^{*}_\\mathrm{el,out} - '
                   'W_\\mathrm{f,dc}$.')
    return cols


# ------------------------------------------------- composite curves ----
def composites(res):
    """comp_a/b/c.pdf: adiabatic, R4, R3, on ONE shared temperature range.

    Two panels each, because the composite alone does not show where the
    pinch is: the left panel is the exchanger, the right is the local
    approach along it, and the point of the pair is that the minimum is
    INTERIOR, at the onset of boiling.
    """
    import boreas_plots as BP
    BP.use_paper_style()
    panels = [('a', 'adiabatic', r'adiabatic limit ($k_r \to 0$)'),
              ('b', 'R4', 'reference case (R4)'),
              ('c', 'R3', 'vertical wells, same slots (R3)')]
    lo, hi = np.inf, -np.inf
    for _, key, _ in panels:
        c, r, k = res[key]
        lo = min(lo, c.T_sink_C, r['rank']['T_1e'] - 273.15)
        hi = max(hi, r['T_2d_realized'] - 273.15)
    lo, hi = lo - 5.0, hi + 8.0
    info = {}
    for tag, key, title in panels:
        c, r, k = res[key]
        fig, axes = plt.subplots(1, 2, figsize=(8.6, 3.5))
        _, nfo = BP.orc_composite(B, c, r['rank'], r['T'], axes=axes)
        axes[0].set_ylim(lo, hi)
        # No outer (a)/(b)/(c) here: orc_composite already labels its own
        # two panels (a) and (b), and a second set of letters on top of
        # them is unreadable. The figure FILE is comp_a/b/c.pdf, which is
        # what the paper cites.
        fig.suptitle(title, fontsize=10, y=1.02)
        fig.tight_layout()
        fig.savefig(f'{OUT}/comp_{tag}.pdf')
        plt.close(fig)
        info[key] = nfo
        print(f'  wrote {OUT}/comp_{tag}.pdf  pinch {nfo["pinch_K"]:.2f} K '
              f'at {nfo["pinch_at_pct"]:.1f} % duty', flush=True)
    json.dump({k: {kk: float(vv) for kk, vv in v.items()}
               for k, v in info.items()},
              open(f'{OUT}/composites.json', 'w'), indent=1)
    return info


def main():
    os.makedirs(OUT, exist_ok=True)
    print('running the four cases...', flush=True)
    res = run_all()
    for key, lab in ORDER:
        c, r, k = res[key]
        print(f"  {lab:34s} loss {100*k['f_formation_loss']:6.2f} %  "
              f"T_2d {r['T_2d_realized']-273.15:6.2f} C  "
              f"eta_ORC {r['rank']['rank_eff']:.4f}  "
              f"wells/MWe {k['wells_per_MWe']:6.2f}", flush=True)
    tab_cycles(res); tab_UA(res); tab_T3e(res)
    cols = tab_ref_results(res)
    try:
        composites(res)
    except Exception as e:
        print('  composites FAILED:', type(e).__name__, e)
    # dump the raw numbers so the macros and the paper can read them
    dump = {key: {kk: (float(vv[0]) if np.isfinite(vv[0]) else None)
                  for kk, vv in cols[key].items()} for key, _ in ORDER}
    for key, _ in ORDER:
        c, r, k = res[key]
        dump[key]['UA_per_MWe'] = k['UA_per_MWe']
        dump[key]['eta_ORC'] = r['rank']['rank_eff']
        dump[key]['T_3e_C'] = r['rank']['T_3e'] - 273.15
        dump[key]['W_net_kW'] = k['W_net_kW']
        for _, tag in EXCH:
            dump[key][f'Q_{tag}_over_Wnet'] = k[f'Q_{tag}_over_Wnet']
            dump[key][f'UA_{tag}_per_MWe'] = k[f'UA_{tag}_per_MWe']
    json.dump(dump, open(f'{OUT}/intensive.json', 'w'), indent=1)
    print(f'  wrote {OUT}/intensive.json')


if __name__ == '__main__':
    main()
