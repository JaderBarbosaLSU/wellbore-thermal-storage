CASE = B.Case(n_segments=99, L_ft=L_MD / 0.3048, t_operation_yr=10.0, **THUMS)


def field(trajectory):
    return G.cached_reference_field(B, CASE, CSV, trajectory=trajectory,
                                    kop_rule='staggered', theta_max=55.0,
                                    kop_ft=300.0, L_md=L_MD, ds=50.0,
                                    verbose=False)


def run_all():
    """The four cases, each a full CSS march with its own indices."""
    out = {}
    # --- adiabatic: no formation at all
    c = CASE.with_(k_rock=1e-9)
    r = B.simulate_css_corrected(c)
    out['adiabatic'] = (c, r, B.performance_indices(c, r))
    # --- R0v: isolated vertical well, no field
    r = B.simulate_css_corrected(CASE)
    out['R0v'] = (CASE, r, B.performance_indices(CASE, r))
    # --- R3 and R4: inside the measured field
    for step, traj in (('R3', 'vertical'), ('R4', 's_curve')):
        md, Rg, tvd, _ = field(traj)
        with G.field_ground(B, md, Rg, tvd):
            r = B.simulate_css_corrected(CASE)
            k = B.performance_indices(CASE, r)
        out[step] = (CASE, r, k)
    return out


def energy_conv(r, n=5):
    """Relative spread of Delta E_dc over the last `n` cycles.

    `cycles` alone is misleading. The CSS loop stops on a state drift of
    1e-9, and for the adiabatic case and R3 that criterion stalls on
    round-off at about 2e-8 J/m, so both report the 80-cycle cap as though
    they had not converged. The ENERGY has: the discharge integral is
    constant to the last digit over those same cycles, which is what the
    results actually depend on. This reports that directly.
    """
    import numpy as _np
    h = r.get('history') or []
    q = _np.array([x['Q_discharge_kJ'] for x in h[-n:]], dtype=float)
    if len(q) < 2 or not q[-1]:
        return float('nan')
    return float((q.max() - q.min()) / abs(q[-1]))


# ------------------------------------------------------------- latex ----
def tex_table(path, caption, label, header, rows, align=None, note=None,
              small=False):
    n = len(header)
    align = align or ('l' + 'r' * (n - 1))
    with open(path, 'w') as f:
        f.write(packstamp.stamp())
        f.write('% GENERATED by mktables.py -- do not edit, do not retype.\n')
        f.write('\\begin{table}[htbp]\n\\centering\n')
        if small:
            f.write('\\footnotesize\n')
        f.write(f'\\caption{{{caption}}}\n\\label{{{label}}}\n')
        f.write(f'\\begin{{tabular}}{{{align}}}\n\\toprule\n')
        f.write(' & '.join(header) + ' \\\\\n\\midrule\n')
        for row in rows:
            f.write(' & '.join(row) + ' \\\\\n')
        f.write('\\bottomrule\n\\end{tabular}\n')
        if note:
            f.write(f'\\\\[2pt]\\footnotesize {note}\n')
        f.write('\\end{table}\n')
    print(f'  wrote {path}')


def f(x, d=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return '--'
    return f'{x:.{d}f}'


# ---------------------------------------------------------- tab_cycles --
EXCH = [('HTHP evaporator', 'hpe'), ('HTHP condenser', 'hpc'),
        ('ORC evaporator', 'orce'), ('ORC condenser', 'orcc')]


def tab_cycles(res):
    """Duties and flows, all intensive.

    There is no separate "per MWe" column for the duties, because
    $Q/W_\\mathrm{net}$ IS the duty in MW per MWe -- the ratio is already
    dimensionless and a second column would print the same number twice.
    """
    c, r, k = res['R4']
    rows = []
    for name, tag in EXCH:
        rows.append([f'{name} duty, $Q/W_\\mathrm{{net}}$',
                     f(k[f'Q_{tag}_over_Wnet'], 2)])
    rows.append(['HTHP electrical input, MW per MWe',
                 f(k['W_el_in_per_MWe'] / 1000.0, 3)])
    rows.append(['charging water flow, kg\\,s$^{-1}$ per MWe',
                 f(k['m_w_ch_per_MWe'], 2)])
    rows.append(['discharging water flow, kg\\,s$^{-1}$ per MWe',
                 f(k['m_w_dc_per_MWe'], 2)])
    rows.append(['\\midrule charge flow per fin tube, kg\\,s$^{-1}$',
                 f(r['m1_ch'], 4)])
    rows.append(['discharge flow per fin tube, kg\\,s$^{-1}$',
                 f(r['m1_dc'], 4)])
    tex_table(f'{OUT}/tab_cycles.tex',
              'Plant duties and flows at the reference case (R4), on an '
              'intensive basis. $W_\\mathrm{net}$ is the realized net output, '
              '$W^{*}_\\mathrm{el,out} - W_\\mathrm{f,dc}$. The HTHP input of '
              f"{k['W_el_in_per_MWe']/1000.0:.2f} MW per MWe is the "
              'reciprocal of $\\eta_\\mathrm{RTE}$ to within the pumping term.',
              'tab:cycles', ['quantity', 'value'], rows, align='lr',
              note='The per-tube flows are the two rows that are NOT per '
                   'MWe, and they do not scale with plant size at all: they '
                   'are pinned by the water glide (Eq.~\\ref{eq:mdot-int}).')


# -------------------------------------------------------------- tab_UA --
def tab_UA(res):
    c, r, k = res['R4']
    rows = []
    for name, tag in EXCH:
        rows.append([name, f(k[f'Q_{tag}_over_Wnet'], 2),
                     f(k[f'UA_{tag}_per_MWe'], 1),
                     f(k[f'dTeff_{tag}_K'], 2), f(k[f'pinch_{tag}_K'], 2)])
    rows.append(['\\midrule total', '--', f(k['UA_per_MWe'], 1), '--',
                 f(k['pinch_min_K'], 2)])
    tex_table(f'{OUT}/tab_UA.tex',
              'Exchanger conductance at the reference case (R4), per MWe of '
              'realized net output. $\\Delta T_\\mathrm{eff}$ and the pinch '
              'are intensive already and are unchanged.',
              'tab:UA',
              ['exchanger', r'$Q/W_\mathrm{net}$',
               r'$UA$ [\si{\kilo\watt\per\kelvin} per MW]',
               r'$\Delta T_\mathrm{eff}$ [\si{\kelvin}]',
               r'pinch [\si{\kelvin}]'], rows, small=True)


